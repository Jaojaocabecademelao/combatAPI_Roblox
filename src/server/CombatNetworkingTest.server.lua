local Shared = game:GetService("ReplicatedStorage"):WaitForChild("Shared")
local Core, Combat = Shared:WaitForChild("Core"), Shared:WaitForChild("Combat")
local World = require(Core.World)
local EntityState = require(Core.EntityState)
local NetworkAdapter = require(Combat.NetworkAdapter)
local NetworkProfile = require(Combat.NetworkProfile)
local NetworkPeer = require(Combat.NetworkPeer)
local NetworkMessage = require(Combat.NetworkMessage)
local NetworkSnapshot = require(Combat.NetworkSnapshot)
local NetworkChannel = require(Combat.NetworkChannel)
local NetworkSequence = require(Combat.NetworkSequence)
local NetworkResult = require(Combat.NetworkResult)
local NetworkEvent = require(Combat.NetworkEvent)
local Input = require(Combat.Input)
local InputState = require(Combat.InputState)
local InputProfile = require(Combat.InputProfile)
local InputComponent = require(Combat.InputComponent)
local InputPacketAdapter = require(Combat.InputPacketAdapter)

local cases = 0
local function check(value, message)
	assert(value, message or ("Network assertion " .. tostring(cases + 1) .. " failed"))
	cases += 1
end
local function fail(result, kind) check(result.Type == kind and not result.Accepted, "Expected " .. kind) end

local sent, registered, unregistered = {}, {}, {}
local mock = NetworkAdapter.new("Mock", {
	Register = function(peer) registered[peer.Id] = true end,
	Unregister = function(peer) unregistered[peer.Id] = true end,
	Send = function(peer, message) table.insert(sent, { Peer = peer.Id, Message = message }); return true end,
})
local reject = NetworkAdapter.new("Reject", { Send = function() return false end })
local profile = NetworkProfile.new({ Channel = NetworkChannel.Input, Reliability = "Reliable", Ordering = "Ordered", BufferSize = 20, SnapshotInterval = 5, InputInterval = 1 })
check(profile.Channel == NetworkChannel.Input, "Profile stores channel")
check(profile.Reliability == "Reliable" and profile.Ordering == "Ordered", "Profile stores transport policy")
check(profile.BufferSize == 20, "Profile stores buffer size")
check(profile.SnapshotInterval == 5 and profile.InputInterval == 1, "Profile stores intervals")
check(not pcall(function() NetworkProfile.new({ Reliability = "Invalid" }) end), "Invalid reliability is rejected")
check(not pcall(function() NetworkProfile.new({ Ordering = "Invalid" }) end), "Invalid ordering is rejected")
local world = World.new({ Network = { Profile = profile, Adapters = { Mock = mock, Reject = reject } } })
local resolver = world:GetNetworkResolver()
check(world:GetNetworkResolver() == resolver, "World exposes stable resolver")
check(resolver:RegisterAdapter("Mock2", mock), "Adapter registers")
check(resolver:GetAdapterDefinition("Mock") == mock, "Adapter retrieves")
check(not resolver:RegisterAdapter("Bad", {}), "Invalid adapter rejects")
check(resolver:RegisterProfile(profile), "Profile registers")
check(resolver:GetProfile(NetworkChannel.Input) == profile, "Profile retrieves")
local peer = NetworkPeer.new("peer-a", NetworkPeer.Role.Client)
local peerB = NetworkPeer.new("peer-b", NetworkPeer.Role.Peer)
check(peer.State == NetworkPeer.State.Disconnected, "Peer starts disconnected")
check(resolver:RegisterPeer(peer).Accepted, "Peer registers")
check(resolver:RegisterPeer(peerB).Accepted, "Second peer registers")
fail(resolver:RegisterPeer(peer), NetworkResult.Type.AlreadyRegistered)
fail(resolver:RegisterPeer({}), NetworkResult.Type.InvalidPeer)
check(resolver:GetPeer("peer-a") == peer, "Peer retrieves")
check(resolver:GetPeer("unknown") == nil, "Unknown peer absent")
check(resolver:Connect("peer-a").Accepted, "Peer connects")
check(peer.State == NetworkPeer.State.Connected, "Connection state is connected")
check(registered["peer-a"], "Adapter receives register")
fail(resolver:Connect("peer-a"), NetworkResult.Type.AlreadyConnected)
fail(resolver:Send("unknown", {}, { Adapter = mock }), NetworkResult.Type.UnknownPeer)
local inputProfile = InputProfile.new()
local inputEntity = world:CreateEntity()
local inputComponent = inputEntity:AddComponent(InputComponent.new(inputProfile))
local inputFrame = world:GetInputResolver():SetInput(inputEntity, Input.Light, InputState.Pressed, 10)
local packetInput = InputPacketAdapter.ToSerializerInput(inputFrame, { Seq = 1 })
local inputMessage = NetworkMessage.new({ Type = NetworkMessage.Type.Input, Channel = NetworkChannel.Input, Sequence = 1, SimulationFrame = 10, Sender = "peer-a", Payload = packetInput })
check(inputMessage.Type == "Input" and inputMessage.Channel == "Input", "Message stores type and channel")
check(inputMessage.Version == NetworkMessage.Version and inputMessage.Version == 1,
	"Messages carry the supported protocol version")
check(inputMessage.Sequence == 1 and inputMessage.SimulationFrame == 10, "Message stores sequence and frame")
check(inputMessage.Sender == "peer-a" and inputMessage.Payload == packetInput, "Message stores sender and payload")
check(resolver:Send("peer-a", inputMessage, { Adapter = mock }).Accepted, "Send succeeds")
check(sent[1].Message == inputMessage, "Adapter receives message")
check(resolver:GetOutgoing("peer-a")[1] == inputMessage, "Outgoing queue stores message")
check(resolver:GetEvents()[#resolver:GetEvents()].Type == NetworkEvent.Type.MessageSent, "Send event emitted")
local snapshot = NetworkSnapshot.new({ SimulationFrame = 11, Sequence = 2, Entities = { [inputEntity.Id] = { Alive = true } }, Components = {} })
check(snapshot.SimulationFrame == 11 and snapshot.Sequence == 2, "Snapshot stores frame and sequence")
check(snapshot.Entities[inputEntity.Id].Alive, "Snapshot stores minimal entity data")
local snapshotMessage = NetworkMessage.new({ Type = NetworkMessage.Type.Snapshot, Channel = NetworkChannel.Snapshot, Sequence = 2, SimulationFrame = 11, Sender = "peer-a", Payload = snapshot })
check(resolver:Send("peer-a", snapshotMessage, { Adapter = mock }).Accepted, "Snapshot sends")
check(resolver:Receive("peer-a", inputMessage).Accepted, "Input receives")
check(resolver:GetIncoming("peer-a")[1] == inputMessage, "Incoming queue stores input")
check(resolver:GetEvents()[#resolver:GetEvents()].Type == NetworkEvent.Type.InputReceived, "InputReceived event emitted")
check(resolver:Receive("peer-a", snapshotMessage).Accepted, "Snapshot receives")
check(resolver:GetEvents()[#resolver:GetEvents()].Type == NetworkEvent.Type.SnapshotReceived, "SnapshotReceived event emitted")
check(resolver:GetLastReceivedSequence("peer-a", NetworkChannel.Input) == 1, "Sequence is tracked per channel")
check(resolver:GetLastReceivedSequence("peer-a", NetworkChannel.Snapshot) == 2, "Sequences are isolated per channel")
local syncMessage = NetworkMessage.new({ Type = NetworkMessage.Type.Synchronization, Channel = NetworkChannel.Sync, Sequence = 1, SimulationFrame = 12, Sender = "peer-a", Payload = { ServerFrame = 12, LocalFrame = 10, Offset = 2 } })
check(resolver:Receive("peer-a", syncMessage).Accepted, "Synchronization receives")
check(resolver:GetEvents()[#resolver:GetEvents()].Type == NetworkEvent.Type.SynchronizationReceived, "Synchronization event emitted")
local duplicate = NetworkMessage.new({ Type = NetworkMessage.Type.Input, Channel = NetworkChannel.Input, Sequence = 1, SimulationFrame = 10, Sender = "peer-a", Payload = packetInput })
fail(resolver:Receive("peer-a", duplicate), NetworkResult.Type.Duplicate)
local old = NetworkMessage.new({ Type = NetworkMessage.Type.Input, Channel = NetworkChannel.Input, Sequence = 0, SimulationFrame = 9, Sender = "peer-a", Payload = packetInput })
fail(resolver:Receive("peer-a", old), NetworkResult.Type.OutOfOrder)
local newer = NetworkMessage.new({ Type = NetworkMessage.Type.Input, Channel = NetworkChannel.Input, Sequence = 3, SimulationFrame = 13, Sender = "peer-a", Payload = packetInput })
check(resolver:Receive("peer-a", newer).Accepted, "Newer sequence receives")
local networkMetrics = resolver:GetMetrics()
check(networkMetrics.Received == 4 and networkMetrics.Duplicates == 1
	and networkMetrics.OutOfOrder == 1 and networkMetrics.Rejected >= 2,
	"Network metrics report delivery and sequence rejection")
check(resolver:GetLastReceivedSequence("peer-a", NetworkChannel.Input) == 3, "Newer sequence updates tracking")
check(not pcall(function()
	NetworkMessage.new({ Version = 2, Type = NetworkMessage.Type.Input,
		Channel = NetworkChannel.Input, SimulationFrame = 14 })
end), "Unsupported message versions are rejected")
fail(resolver:Receive("peer-a", {}), NetworkResult.Type.InvalidMessage)
fail(resolver:Receive("peer-a", NetworkMessage.new({ Type = NetworkMessage.Type.Event, Channel = NetworkChannel.Input, Sequence = 4, SimulationFrame = 14, Payload = {} })), NetworkResult.Type.InvalidChannel)
fail(resolver:Receive("unknown", inputMessage), NetworkResult.Type.UnknownPeer)
local invalidFrame = NetworkMessage.new({ Type = NetworkMessage.Type.Event, Channel = NetworkChannel.Events, Sequence = 1, SimulationFrame = 15, Payload = {} })
check(resolver:Receive("peer-a", invalidFrame).Accepted, "Event message receives")
fail(resolver:Acknowledge("unknown", 1, 10), NetworkResult.Type.UnknownPeer)
fail(resolver:Acknowledge("peer-a", "bad", 10), NetworkResult.Type.AckFailed)
check(resolver:Acknowledge("peer-a", 3, 13).Accepted, "Acknowledgement succeeds")
check(resolver:GetEvents()[#resolver:GetEvents()].Type == NetworkEvent.Type.Acknowledged, "Acknowledged event emitted")
check(resolver:Broadcast(NetworkMessage.new({ Type = NetworkMessage.Type.Event, Channel = NetworkChannel.Events, Sequence = 1, SimulationFrame = 16, Payload = { Kind = "Notice" } }), { Adapter = mock }).Accepted, "Broadcast succeeds")
check(#sent >= 3, "Broadcast sends through adapter")
check(resolver:Send("peer-a", newer, { Adapter = reject }).Type == NetworkResult.Type.SendFailed, "Adapter failure is explicit")
check(resolver:Disconnect("peer-a").Accepted, "Peer disconnects")
check(peer.State == NetworkPeer.State.Disconnected, "Disconnect state is explicit")
check(unregistered["peer-a"], "Adapter receives unregister")
fail(resolver:Send("peer-a", inputMessage, { Adapter = mock }), NetworkResult.Type.NotConnected)
check(resolver:Connect("peer-a").Accepted, "Peer reconnects")
local sequence = NetworkSequence.new(10, 16)
check(sequence.Value == 10, "Sequence stores value")
check(sequence:Next() == 11, "Sequence increments")
check(sequence:IsNewer(10), "Sequence compares newer")
check(sequence:IsOlder(12), "Sequence compares older")
check(sequence:Compare(11) == 0, "Sequence compares equal")
local wrap = NetworkSequence.new(15, 16)
check(wrap:Next() == 0, "Sequence wraps")
check(wrap:IsNewer(15), "Wrapped sequence remains newer")
check(NetworkChannel.Input == "Input" and NetworkChannel.Snapshot == "Snapshot", "Channels are abstract")
check(NetworkMessage.Type.Command == "Command", "Command is transport type only")
check(resolver:GetConnectionState("peer-a") == NetworkPeer.State.Connected, "Connection query works")
check(type(resolver.GetIncoming) == "function" and type(resolver.GetOutgoing) == "function", "Queue API exists")
check(type(resolver.GetLastReceivedSequence) == "function", "Sequence query API exists")
check(inputComponent.EntityId == inputEntity.Id, "Networking does not replace input component")
check(world:GetEntity(inputEntity.Id) == inputEntity, "Networking preserves entity")
check(inputEntity.State == EntityState.Alive, "Networking does not change gameplay state")
check(resolver.World == world, "Resolver retains world reference without mutating it")
check(type(resolver.CreateSnapshot) == "function", "Snapshot factory exists")
check(type(resolver.GetEvents) == "function" and type(resolver.GetResults) == "function", "History API exists")
check(#world:GetNetworkEvents() == #resolver:GetEvents(), "World exposes network events")
check(#world:GetNetworkResults() == #resolver:GetResults(), "World exposes network results")
for _, channel in ipairs({ NetworkChannel.Input, NetworkChannel.Simulation, NetworkChannel.Snapshot, NetworkChannel.Events, NetworkChannel.Sync }) do
	check(type(channel) == "string", "Channel enum is string")
	check(resolver:GetProfile(channel) ~= nil or channel ~= NetworkChannel.Input, "Profile lookup is safe")
end
for _, messageType in ipairs({
	NetworkMessage.Type.Input,
	NetworkMessage.Type.Snapshot,
	NetworkMessage.Type.Acknowledgement,
	NetworkMessage.Type.Synchronization,
	NetworkMessage.Type.Command,
	NetworkMessage.Type.Event,
}) do
	check(type(messageType) == "string", "Message type enum is string")
end
check(mock:Validate(inputMessage), "Mock adapter validates envelope")
check(mock:Call("MissingMethod"), "Missing adapter hooks are neutral")
check(reject:Call("Send", peer, inputMessage) == false, "Reject adapter reports failure")
check(type(NetworkResult.Type.Success) == "string", "Result types are explicit")
check(type(NetworkEvent.Type.MessageSent) == "string", "Event types are explicit")
check(type(inputFrame.Frame) == "number", "Input packet retains simulation frame")
check(packetInput.buttons ~= nil, "Input packet contains button bitmask")
check(packetInput.seq == 1, "Input packet retains sequence")
check(packetInput.playerId == nil, "Input packet does not invent player identity")
check(inputEntity:GetComponent(InputComponent) == inputComponent, "Input component remains local")
check(resolver.CurrentFrame == 0, "Network resolver does not advance simulation")
check(world.CurrentFrame == 0, "Network traffic does not advance world")
check(snapshot.Components ~= nil, "Snapshot component section is explicit")
check(snapshotMessage.Payload == snapshot, "Snapshot payload is not flattened")
local receivedInputAt13 = false
for _, message in ipairs(resolver:GetIncoming("peer-a")) do
	if message.Type == NetworkMessage.Type.Input and message.SimulationFrame == 13 then receivedInputAt13 = true end
end
check(receivedInputAt13, "Incoming queue preserves each message frame")
check(resolver:GetOutgoing("peer-a")[1].SimulationFrame == 10, "Outgoing queue preserves frame")
check(resolver:GetConnectionState("peer-b") == NetworkPeer.State.Disconnected, "Unconnected peer remains disconnected")
check(resolver:Disconnect("peer-b").Accepted, "Disconnected peer can be cleaned up")
check(resolver:UnregisterPeer("peer-b").Accepted, "Second peer unregisters")
fail(resolver:UnregisterPeer("peer-b"), NetworkResult.Type.UnknownPeer)
check(resolver:GetPeer("peer-b") == nil, "Peer cleanup removes peer")
check(resolver:Connect("peer-b").Type == NetworkResult.Type.UnknownPeer, "Removed peer cannot reconnect")
check(type(resolver.CreateSnapshot) == "function", "Snapshot creation is explicit")
for _, method in ipairs({
	"RegisterProfile", "GetProfile", "RegisterAdapter", "GetAdapterDefinition",
	"RegisterPeer", "GetPeer", "UnregisterPeer", "Connect", "Disconnect",
	"Send", "Broadcast", "Receive", "Acknowledge", "CreateSnapshot",
	"GetIncoming", "GetOutgoing", "GetLastReceivedSequence",
	"GetConnectionState", "GetEvents", "GetResults", "Clear",
}) do
	check(type(resolver[method]) == "function", "Resolver exposes " .. method)
end
for _, role in ipairs({ NetworkPeer.Role.Client, NetworkPeer.Role.Server, NetworkPeer.Role.Peer }) do
	check(type(role) == "string", "Peer role enum is string")
end
for _, state in ipairs({
	NetworkPeer.State.Disconnected,
	NetworkPeer.State.Connecting,
	NetworkPeer.State.Connected,
	NetworkPeer.State.Disconnecting,
}) do
	check(type(state) == "string", "Peer state enum is string")
end
check(type(NetworkAdapter.new) == "function", "Adapter constructor is available")
check(type(NetworkProfile.new) == "function", "Profile constructor is available")
check(type(NetworkPeer.new) == "function", "Peer constructor is available")
check(type(NetworkMessage.new) == "function", "Message constructor is available")
check(type(NetworkSnapshot.new) == "function", "Snapshot constructor is available")
check(type(NetworkSequence.new) == "function", "Sequence constructor is available")
check(type(InputPacketAdapter.ToSerializerInput) == "function", "Input bridge is available")
check(type(InputPacketAdapter.ToButtons) == "function", "Input bitmask bridge is available")
check(type(InputPacketAdapter.GetInputMap) == "function", "Input map bridge is available")
check(InputPacketAdapter.GetBit(Input.Light) == 64, "Input bit assignment is stable")
check(InputPacketAdapter.GetBit(Input.Guard) == 1024, "Guard bit assignment is stable")
check(packetInput.move.X == 0 and packetInput.aim.Z == 1, "Input defaults are explicit")
check(resolver:GetOutgoing("unknown")[1] == nil, "Unknown outgoing queue is empty")
check(resolver:GetIncoming("unknown")[1] == nil, "Unknown incoming queue is empty")
check(resolver:GetLastReceivedSequence("unknown", NetworkChannel.Input) == nil, "Unknown sequence is empty")
check(resolver:GetConnectionState("unknown") == nil, "Unknown connection state is empty")
check(type(NetworkChannel.Input) == "string", "Input channel is public")
check(type(NetworkChannel.Simulation) == "string", "Simulation channel is public")
check(type(NetworkChannel.Snapshot) == "string", "Snapshot channel is public")
check(type(NetworkChannel.Events) == "string", "Events channel is public")
check(type(NetworkChannel.Sync) == "string", "Sync channel is public")
check(type(NetworkMessage.Type.Input) == "string", "Input message type is public")
check(type(NetworkMessage.Type.Snapshot) == "string", "Snapshot message type is public")
check(type(NetworkMessage.Type.Acknowledgement) == "string", "ACK message type is public")
check(type(NetworkMessage.Type.Synchronization) == "string", "Sync message type is public")
check(type(NetworkMessage.Type.Command) == "string", "Command message type is public")
check(type(NetworkMessage.Type.Event) == "string", "Event message type is public")
check(type(NetworkEvent.Type.Connected) == "string", "Connected event is public")
check(type(NetworkEvent.Type.Disconnected) == "string", "Disconnected event is public")
check(type(NetworkEvent.Type.SequenceRejected) == "string", "Sequence event is public")
check(type(NetworkResult.Type.InvalidFrame) == "string", "Invalid frame result is public")
resolver:Clear()
check(#resolver:GetEvents() == 0 and #resolver:GetResults() == 0, "Network history clears")
print("Combat networking tests passed (" .. tostring(cases) .. " cases)")
