local Shared = game:GetService("ReplicatedStorage"):WaitForChild("Shared")
local Core, Combat = Shared:WaitForChild("Core"), Shared:WaitForChild("Combat")
local World = require(Core.World)
local EntityState = require(Core.EntityState)
local CharacterProfile = require(Combat.CharacterProfile)
local CharacterAdapter = require(Combat.CharacterAdapter)
local AnimationDefinition = require(Combat.AnimationDefinition)
local AnimationProfile = require(Combat.AnimationProfile)
local AnimationAdapter = require(Combat.AnimationAdapter)
local AnimationTrack = require(Combat.AnimationTrack)
local AnimationResult = require(Combat.AnimationResult)
local AnimationEvent = require(Combat.AnimationEvent)
local CharacterResult = require(Combat.CharacterResult)

local cases = 0
local function check(value, message)
	assert(value, message or ("Animation assertion " .. tostring(cases + 1) .. " failed"))
	cases += 1
end
local function fail(result, kind) check(result.Type == kind and not result.Accepted, "Expected " .. kind) end

local calls, rejectPlay = {}, false
local mock = AnimationAdapter.new("Mock", {
	IsValid = function(entity, definition) return entity ~= nil and definition ~= nil end,
	Play = function(track) table.insert(calls, "Play:" .. track.AnimationId); return not rejectPlay end,
	Pause = function(track) table.insert(calls, "Pause:" .. track.TrackId) end,
	Resume = function(track) table.insert(calls, "Resume:" .. track.TrackId) end,
	Stop = function(track) table.insert(calls, "Stop:" .. track.TrackId) end,
	SetSpeed = function(track, value) table.insert(calls, "Speed:" .. value) end,
	SetWeight = function(track, value) table.insert(calls, "Weight:" .. value) end,
	SetPriority = function(track, value) table.insert(calls, "Priority:" .. tostring(value)) end,
})
local secondary = AnimationAdapter.new("Secondary", { IsValid = function() return true end })
local definition = AnimationDefinition.new({
	Id = "LightAttack", AssetId = "asset://light", DurationFrames = 30,
	Loop = false, Priority = "Action", Speed = 1, Weight = 1,
	Markers = { Active = 5 }, Data = { Category = "Attack" },
})
local loop = AnimationDefinition.new({ Id = "Idle", DurationFrames = 60, Loop = true, Priority = "Idle" })
local profile = AnimationProfile.new({ Id = "FighterAnimations", Definitions = { definition, loop } })
check(definition.Id == "LightAttack", "Definition stores id")
check(definition.AssetId == "asset://light", "Definition stores asset metadata")
check(definition.DurationFrames == 30, "Definition stores duration")
check(not definition.Loop, "Definition stores non-loop policy")
check(definition.Priority == "Action", "Definition stores priority")
check(definition.Speed == 1 and definition.Weight == 1, "Definition stores playback defaults")
check(definition.Markers.Active == 5, "Definition stores marker data")
check(definition.Data.Category == "Attack", "Definition stores extensible data")
check(not pcall(function() AnimationDefinition.new({ Id = "Bad", DurationFrames = 0 }) end), "Invalid duration rejected")
check(profile:Get("LightAttack") == definition, "Profile retrieves definition")
check(profile:Get("Idle") == loop, "Profile stores loop definition")
check(profile.Defaults ~= nil, "Profile has defaults")
check(profile.Definitions ~= definition, "Profile stores registry separately")
check(mock.Id == "Mock", "Mock adapter has identity")
check(secondary.Id == "Secondary", "Adapters coexist")
check(type(mock.Validate) == "function" and type(mock.Call) == "function", "Adapter contract exists")
local world = World.new({ Animation = { Adapters = { Mock = mock, Secondary = secondary } } })
local resolver = world:GetAnimationResolver()
check(world:GetAnimationResolver() == resolver, "World exposes stable animation resolver")
check(resolver:RegisterProfile(profile), "Animation profile registers")
check(resolver:GetProfile(profile.Id) == profile, "Animation profile retrieves")
check(resolver:GetAnimation("LightAttack") == definition, "Registered definition retrieves")
check(resolver:GetAnimation("Unknown") == nil, "Unknown definition absent")
check(resolver:RegisterAdapter("Mock2", secondary), "Second adapter registers")
check(resolver:GetAdapterDefinition("Mock2") == secondary, "Second adapter retrieves")
check(not resolver:RegisterAnimation({}), "Invalid definition rejected")
check(not resolver:RegisterAdapter("Bad", {}), "Invalid adapter rejected")
local characterAdapter = CharacterAdapter.new("Custom", { IsValid = function(value) return value.Valid end })
local characterProfile = CharacterProfile.new({ CharacterId = "Fighter", AdapterId = "Custom" })
check(world:GetCharacterResolver():RegisterProfile(characterProfile), "Character profile registers")
check(world:GetCharacterResolver():RegisterAdapter("Custom", characterAdapter), "Character adapter registers")
local entityA, entityB = world:CreateEntity(), world:CreateEntity()
local charA = { Valid = true, Name = "A" }
check(world:GetCharacterResolver():Attach(entityA, charA, { Profile = characterProfile, Frame = 10 }).Accepted, "Character A attaches")
check(world:GetCharacterResolver():Attach(entityB, { Valid = true, Name = "B" }, { Profile = characterProfile, Frame = 10 }).Accepted, "Character B attaches")
local started = resolver:Play(entityA, "LightAttack", { Frame = 100 })
check(started.Accepted, "Play succeeds")
check(started.TrackId ~= nil, "Play returns track id")
local track = resolver:GetTrack(started.TrackId)
check(track ~= nil, "Track is created")
check(track.TrackId == started.TrackId, "Track identity is stable")
check(track.EntityId == entityA.Id, "Track stores entity id")
check(track.AnimationId == "LightAttack", "Track stores animation id")
check(track.StartFrame == 100, "Track stores start frame")
check(track.State == AnimationTrack.State.Playing, "Track starts playing")
check(track.Speed == 1 and track.Weight == 1, "Track copies runtime defaults")
check(track.Priority == "Action", "Track copies priority")
check(calls[1] == "Play:LightAttack", "Adapter receives Play")
check(resolver:GetEvents()[1].Type == AnimationEvent.Type.Started, "Started event emitted")
check(resolver:GetEvents()[1].TrackId == track.TrackId, "Started event stores track")
check(resolver:GetEvents()[1].Frame == 100, "Started event stores frame")
check(resolver:IsPlaying(track.TrackId), "IsPlaying is true")
check(not resolver:IsPaused(track.TrackId), "New track is not paused")
check(not resolver:IsStopped(track.TrackId), "New track is not stopped")
check(#resolver:GetTracks(entityA) == 1, "Entity has one track")
fail(resolver:Play(entityA, "LightAttack", { Frame = 101 }), AnimationResult.Type.AlreadyPlaying)
local paused = resolver:Pause(track.TrackId, { Frame = 105 })
check(paused.Accepted, "Pause succeeds")
check(resolver:IsPaused(track.TrackId), "Track becomes paused")
check(track.CurrentFrame == 105, "Pause records frame")
check(calls[#calls] == "Pause:" .. track.TrackId, "Adapter receives Pause")
check(resolver:GetEvents()[#resolver:GetEvents()].Type == AnimationEvent.Type.Paused, "Pause event emitted")
fail(resolver:Pause(track.TrackId, { Frame = 106 }), AnimationResult.Type.AlreadyPaused)
fail(resolver:Resume(99999, { Frame = 106 }), AnimationResult.Type.InvalidTrack)
local resumed = resolver:Resume(track.TrackId, { Frame = 107 })
check(resumed.Accepted, "Resume succeeds")
check(resolver:IsPlaying(track.TrackId), "Resume restores Playing")
check(calls[#calls] == "Resume:" .. track.TrackId, "Adapter receives Resume")
check(resolver:GetEvents()[#resolver:GetEvents()].Type == AnimationEvent.Type.Resumed, "Resume event emitted")
fail(resolver:Resume(track.TrackId, { Frame = 108 }), AnimationResult.Type.NotPaused)
check(resolver:SetSpeed(track.TrackId, 2, { Frame = 109 }).Accepted, "Speed changes")
check(track.Speed == 2, "Speed is track-local")
check(resolver:SetWeight(track.TrackId, 0.75, { Frame = 109 }).Accepted, "Weight changes")
check(track.Weight == 0.75, "Weight is track-local")
check(resolver:SetPriority(track.TrackId, "Override", { Frame = 109 }).Accepted, "Priority changes")
check(track.Priority == "Override", "Priority is track-local")
check(resolver:Advance(entityA, 112)[1].ElapsedFrames == 12, "Advance uses frame timing")
check(track.CurrentFrame == 112, "Advance updates current frame")
local stopped = resolver:Stop(track.TrackId, { Frame = 115 })
check(stopped.Accepted, "Stop succeeds")
check(resolver:IsStopped(track.TrackId), "Track becomes stopped")
check(calls[#calls] == "Stop:" .. track.TrackId, "Adapter receives Stop")
check(resolver:GetEvents()[#resolver:GetEvents()].Type == AnimationEvent.Type.Stopped, "Stop event emitted")
fail(resolver:Stop(track.TrackId, { Frame = 116 }), AnimationResult.Type.AlreadyStopped)
fail(resolver:Resume(track.TrackId, { Frame = 117 }), AnimationResult.Type.NotPaused)
local completedTrack = resolver:Play(entityA, "LightAttack", { Frame = 120 })
check(resolver:NotifyCompleted(completedTrack.TrackId, 150).Type == AnimationResult.Type.Completed, "Completion succeeds")
check(resolver:GetTrack(completedTrack.TrackId).State == AnimationTrack.State.Completed, "Track becomes completed")
check(resolver:GetEvents()[#resolver:GetEvents()].Type == AnimationEvent.Type.Completed, "Completion event emitted")
local loopTrack = resolver:Play(entityB, "Idle", { Frame = 200 })
check(loopTrack.Accepted, "Loop animation plays")
check(resolver:NotifyCompleted(loopTrack.TrackId, 260).Accepted, "Loop notification remains active")
check(resolver:GetTrack(loopTrack.TrackId).State == AnimationTrack.State.Playing, "Loop does not complete")
check(resolver:GetTrack(loopTrack.TrackId).ElapsedFrames == 0, "Loop elapsed frames wrap")
check(resolver:GetTracks(entityB)[1].EntityId == entityB.Id, "Entity B track is isolated")
check(resolver:GetTrack(track.TrackId).Speed == 2, "Track A speed is isolated")
check(resolver:GetTrack(loopTrack.TrackId).Speed == 1, "Track B speed is isolated")
check(definition.Speed == 1, "Definition speed is immutable at runtime")
check(definition.Weight == 1, "Definition weight is immutable at runtime")
check(resolver:GetAnimation("LightAttack") == definition, "Shared definition remains registered")
local noCharacter = world:CreateEntity()
fail(resolver:Play(noCharacter, "Idle", { Frame = 300 }), AnimationResult.Type.NotAttached)
local invalidCharacter = world:GetCharacterResolver():Attach(noCharacter, { Valid = false }, { Profile = characterProfile, Frame = 301 })
check(invalidCharacter.Type == CharacterResult.Type.AdapterRejected, "Invalid character is rejected before animation")
local detachedResult = world:GetCharacterResolver():Detach(entityA, { Frame = 302 })
check(detachedResult.Accepted, "Character detach succeeds")
fail(resolver:Play(entityA, "Idle", { Frame = 303 }), AnimationResult.Type.NotAttached)
check(world:GetCharacterResolver():Attach(entityA, { Valid = true }, { Profile = characterProfile, Frame = 304 }).Accepted, "Reattach restores animation eligibility")
check(resolver:Play(entityA, "Idle", { Frame = 305 }).Accepted, "Play after reattach succeeds")
rejectPlay = true
local rejected = resolver:Play(entityB, "LightAttack", { Frame = 306 })
fail(rejected, AnimationResult.Type.PlayFailed)
check(#resolver:GetTracks(entityB) == 1, "Failed Play does not add partial track")
rejectPlay = false
local dead = world:CreateEntity(); dead.State = EntityState.Dead
fail(resolver:Play(dead, "Idle", { Frame = 307 }), AnimationResult.Type.EntityDead)
fail(resolver:Play(99999, "Idle", { Frame = 308 }), AnimationResult.Type.InvalidEntity)
fail(resolver:Play(entityA, "Unknown", { Frame = 309 }), AnimationResult.Type.InvalidAnimation)
check(resolver:GetResults()[1] ~= nil, "Results are retained")
check(resolver:GetEvents()[1].EntityId == entityA.Id, "Events include entity")
check(type(resolver.GetTrack) == "function" and type(resolver.GetTracks) == "function", "Track query API exists")
check(type(resolver.NotifyCompleted) == "function", "Completion API exists")
check(type(resolver.On) == "function", "Event subscription API exists")
local observed = 0
resolver:On(AnimationEvent.Type.Started, function(event) observed += event.EntityId > 0 and 1 or 0 end)
check(resolver:Play(entityB, "LightAttack", { Frame = 310 }).Accepted, "Listener play succeeds")
check(observed == 1, "Listener observes Started")
check(world:GetAnimationResolver() == resolver, "World resolver remains stable")
check(#world:GetAnimationEvents() == #resolver:GetEvents(), "World exposes current events")
check(#world:GetAnimationResults() == #resolver:GetResults(), "World exposes current results")
check(AnimationTrack.State.Stopped == "Stopped", "Track has Stopped state")
check(AnimationTrack.State.Playing == "Playing", "Track has Playing state")
check(AnimationTrack.State.Paused == "Paused", "Track has Paused state")
check(AnimationTrack.State.Completed == "Completed", "Track has Completed state")
check(resolver:IsPlaying(loopTrack.TrackId), "Loop remains playing after completion notification")
check(not resolver:IsPaused(loopTrack.TrackId), "Loop is not paused")
check(not resolver:IsStopped(loopTrack.TrackId), "Loop is not stopped")
check(resolver:GetTrack(loopTrack.TrackId).Definition == loop, "Track references shared definition")
check(resolver:GetTrack(completedTrack.TrackId).Definition == definition, "Completed track keeps definition")
check(resolver:GetTrack(completedTrack.TrackId).ElapsedFrames == 0, "Completion does not corrupt elapsed data")
check(resolver:GetTracks(entityA)[1].EntityId == entityA.Id, "Entity A track query is isolated")
check(resolver:GetTracks(entityB)[1].EntityId == entityB.Id, "Entity B track query is isolated")
check(resolver:GetTracks(noCharacter)[1] == nil, "Entity without character has no tracks")
check(resolver:GetAdapterDefinition("Mock") == mock, "Mock adapter remains registered")
check(resolver:GetAdapterDefinition("Secondary") == secondary, "Secondary adapter remains registered")
check(resolver:RemoveAdapter("Mock2"), "Registered adapter can be removed")
check(resolver:GetAdapterDefinition("Mock2") == nil, "Removed adapter cannot be retrieved")
check(resolver:RegisterAdapter("Mock2", secondary), "Removed adapter can be registered again")
check(resolver:RemoveAnimation("Unknown"), "Removing unknown animation is deterministic")
check(resolver:RegisterAnimation(definition), "Existing definition can be registered again")
check(profile:Remove("Unknown") == profile, "Profile removes unknown definition safely")
check(profile:Register(definition) == profile, "Profile can restore definition")
check(profile:Get("LightAttack") == definition, "Profile definition remains stable")
check(resolver:GetProfile("FighterAnimations").Id == "FighterAnimations", "Profile identity is stable")
check(definition.Markers.Active == 5, "Marker data remains available after playback")
check(definition.Data.Category == "Attack", "Definition data remains available after playback")
check(track.Definition.Speed == 1, "Track definition is not runtime-mutated")
check(track.Definition.Weight == 1, "Track definition weight is not runtime-mutated")
check(resolver:SetSpeed(loopTrack.TrackId, 0.5, { Frame = 320 }).Accepted, "Loop speed changes")
check(resolver:GetTrack(loopTrack.TrackId).Speed == 0.5, "Loop speed is independent")
check(resolver:SetWeight(loopTrack.TrackId, 0.25, { Frame = 320 }).Accepted, "Loop weight changes")
check(resolver:GetTrack(loopTrack.TrackId).Weight == 0.25, "Loop weight is independent")
check(resolver:SetPriority(loopTrack.TrackId, 2, { Frame = 320 }).Accepted, "Numeric priority is supported")
check(resolver:GetTrack(loopTrack.TrackId).Priority == 2, "Numeric priority is stored")
fail(resolver:SetSpeed(loopTrack.TrackId, -1, { Frame = 321 }), AnimationResult.Type.InvalidTrack)
fail(resolver:SetWeight(loopTrack.TrackId, -1, { Frame = 321 }), AnimationResult.Type.InvalidTrack)
fail(resolver:SetPriority(loopTrack.TrackId, {}, { Frame = 321 }), AnimationResult.Type.InvalidTrack)
fail(resolver:Pause(99999, { Frame = 322 }), AnimationResult.Type.InvalidTrack)
fail(resolver:Stop(99999, { Frame = 323 }), AnimationResult.Type.InvalidTrack)
fail(resolver:NotifyCompleted(99999, 324), AnimationResult.Type.InvalidTrack)
check(resolver:Advance(entityB, 325)[1].CurrentFrame == 325, "Advance remains frame-based")
check(resolver:GetTrack(loopTrack.TrackId).ElapsedFrames == 125, "Advance preserves elapsed frame count")
check(entityA.State == EntityState.Alive, "Animation does not alter entity state")
check(world:GetCharacterResolver():IsAttached(entityA), "Animation does not detach character")
check(world:GetCharacterResolver():IsAttached(entityB), "Animation does not alter other character")
check(world:GetCharacterResolver():GetCharacter(entityA).CharacterId == "Fighter", "Animation preserves character identity")
resolver:Clear()
check(#resolver:GetEvents() == 0 and #resolver:GetResults() == 0, "Resolver history clears")
print("Combat animation tests passed (" .. tostring(cases) .. " cases)")
