	local attack = Attack.new({ Id = "combo-integration", Damage = 12, Hitstun = 4 })
	local instance = AttackInstance.new(attack, ia):Activate()
	local hitbox = Hitbox.new({ Owner = ia, Position = Vector3.new(0, 0, 0), Size = Vector3.new(4, 4, 4) })
	local hurtbox = Hurtbox.new({ Owner = ib, Position = Vector3.new(0, 0, 0), Size = Vector3.new(4, 4, 4) })
