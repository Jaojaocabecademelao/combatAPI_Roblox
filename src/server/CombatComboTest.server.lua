	check(#duplicateResolver:GetEvents() == 2, "Duplicate input does not duplicate semantic events")
	local unattachedWorld = World.new()
	local unattachedA, unattachedB = unattachedWorld:CreateEntity(), unattachedWorld:CreateEntity()
	local unattachedResolver = unattachedWorld:GetComboResolver()
