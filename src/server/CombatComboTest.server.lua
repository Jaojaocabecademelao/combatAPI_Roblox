local cases = 0
local function check(condition, message)
	assert(condition, message or ("Combo assertion " .. tostring(cases + 1) .. " failed"))
	cases += 1
end
local function fixture(options)
	local world = World.new({ ComboProfile = options })
	local attacker, defender = world:CreateEntity(), world:CreateEntity()
	local component = attacker:AddComponent(ComboComponent.new())
	local resolver = world:GetComboResolver()
	local serial = 0
	local function hit(frame, damage, attackId, target, source)
		serial += 1
		target = target or defender
		return HitEvent.new({ AttackInstance = { Id = attackId or (1000 + serial) },
			AttackInstanceId = attackId or (1000 + serial), Attacker = source or attacker, Target = target,
			AttackerEntityId = (source or attacker).Id, TargetEntityId = target.Id,
			HitboxId = serial * 2, HurtboxId = serial * 2 + 1, Frame = frame,
			Damage = damage or 0, Hitstun = 5, OffensiveProperties = { Damage = damage or 0, Hitstun = 5 } })
	end
	return world, attacker, defender, component, resolver, hit
end
local function process(resolver, hits, frame, extras)
	extras = extras or {}
	return resolver:Process(hits or {}, extras.Defense or {}, extras.Damage or {}, extras.Counter or {}, frame,
		extras.Death or {}, extras.Guard or {}, extras.Armor, extras.ReactionHits)
end

