	check(integratedWorld:GetComboResolver():GetCombo(ia, ib).HitCount == 1, "Collision-to-World flow creates combo")
	check(integratedWorld:GetComboResolver():GetCombo(ia, ib).Damage == 12, "World combo uses resolved DamageEvent amount")
	check(integratedWorld:GetComboEvents()[2].HitEvent.AttackInstance == instance, "Integration preserves AttackInstance identity")
	check(integratedWorld:GetComboEvents()[2].Frame == 1, "Integration records simulation frame")
	check(integratedWorld:GetComboResults()[1].Type == ComboResult.Type.Started, "World exposes structured ComboResults")
	check(integratedWorld:GetDamageEvents()[1].AppliedAmount == 12, "Damage remains owned by DamageResolver")
	check(ib:GetComponent(HealthComponent):GetHealth() == 88, "Combo tracking does not replace health resolution")
