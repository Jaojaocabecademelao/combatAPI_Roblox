	check(unattachedResolver:GetCombo(unattachedA, unattachedB) == nil, "Missing ComboComponent does not fabricate storage")
	check(unattachedResolver:GetResults()[1].Reason == "MissingComboComponent", "Missing component is an explicit ignored result")
	local integratedWorld = World.new()
