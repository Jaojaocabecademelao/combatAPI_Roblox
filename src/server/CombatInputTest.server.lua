local Shared = game:GetService("ReplicatedStorage"):WaitForChild("Shared")
local Core, Combat = Shared:WaitForChild("Core"), Shared:WaitForChild("Combat")
local World = require(Core.World)
local Input = require(Combat.Input)
local InputState = require(Combat.InputState)
local InputProfile = require(Combat.InputProfile)
local InputComponent = require(Combat.InputComponent)
local InputEvent = require(Combat.InputEvent)
local InputBuffer = require(Combat.InputBuffer)
local InputPacketAdapter = require(Combat.InputPacketAdapter)

local cases = 0
local function check(value, message)
	assert(value, message or ("Input assertion " .. tostring(cases + 1) .. " failed"))
	cases += 1
end

local profile = InputProfile.new({ BufferSize = 5, InputTimeoutFrames = 5 })
profile:Bind("Keyboard_W", Input.Forward):Bind("Mouse1", Input.Light):Bind("Pad_X", Input.Light)
check(profile:IsValidInput(Input.Light), "Light is valid")
check(profile:IsValidInput(Input.Forward), "Forward is valid")
check(profile:GetBinding("Keyboard_W") == Input.Forward, "Binding maps external input")
check(profile:GetBinding("Mouse1") == Input.Light, "Binding supports another source")
check(profile:GetBinding("Pad_X") == Input.Light, "Multiple bindings share an input")
profile:Bind("Keyboard_W", Input.Back)
check(profile:GetBinding("Keyboard_W") == Input.Back, "Rebind replaces deterministically")
profile:Unbind("Keyboard_W")
check(profile:GetBinding("Keyboard_W") == nil, "Unbind removes only configuration")
check(not pcall(function() InputProfile.new({ BufferSize = 0 }) end), "Invalid buffer size is rejected")
check(not pcall(function() InputProfile.new({ InputTimeoutFrames = -1 }) end), "Invalid timeout is rejected")
check(not pcall(function() profile:Bind("Bad", "Unknown") end), "Invalid combat input is rejected")
local pureBuffer = InputBuffer.new(2)
local firstFrame, secondFrame, thirdFrame = { Frame = 10 }, { Frame = 12 }, { Frame = 11 }
pureBuffer:Put(firstFrame.Frame, firstFrame)
pureBuffer:Put(secondFrame.Frame, secondFrame)
pureBuffer:Put(thirdFrame.Frame, thirdFrame)
check(pureBuffer:Count() == 2, "Pure frame buffer is bounded")
check(pureBuffer:Get(10) == nil, "Pure frame buffer prunes the oldest frame")
check(pureBuffer:Get(11) == thirdFrame and pureBuffer:Get(12) == secondFrame,
	"Pure frame buffer accepts out-of-order frames deterministically")
check(pureBuffer:GetWindow(11, 12)[1] == thirdFrame, "Pure buffer windows are frame ordered")
pureBuffer:Clear()
check(pureBuffer:Count() == 0, "Pure frame buffer can be cleared")
for _, inputId in pairs(Input) do
	check(profile:IsValidInput(inputId), "Every official input is valid: " .. inputId)
end

local world = World.new({ InputProfile = InputProfile.new({ BufferSize = 5 }) })
local resolver = world:GetInputResolver()
local a, b, c = world:CreateEntity(), world:CreateEntity(), world:CreateEntity()
local ca = a:AddComponent(InputComponent.new(resolver.Profile))
local cb = b:AddComponent(InputComponent.new(resolver.Profile))
c:AddComponent(InputComponent.new(resolver.Profile))
check(ca:GetState(Input.Light) == InputState.None, "Component starts with None")
check(resolver:GetInput(a, Input.Light) == InputState.None, "Resolver reads None")
check(not resolver:IsPressed(a, Input.Light), "None is not Pressed")
check(not resolver:IsHeld(a, Input.Light), "None is not Held")
check(not resolver:IsReleased(a, Input.Light), "None is not Released")
local frame = resolver:SetInput(a, Input.Light, InputState.Pressed, 100, { Source = "Test" })
check(frame.Frame == 100 and frame.EntityId == a.Id, "InputFrame stores frame and entity")
check(frame.Inputs[Input.Light] == InputState.Pressed, "Pressed is stored in InputFrame")
check(InputPacketAdapter.GetBit(Input.Light) == 64, "Input packet bit assignment is stable")
check(InputPacketAdapter.ToButtons(frame) == 64, "Pressed input is encoded as an active button")
local serializerInput = InputPacketAdapter.ToSerializerInput(frame, { Seq = 7 })
check(serializerInput.seq == 7 and serializerInput.timestamp == 100, "Serializer adapter preserves packet metadata")
check(serializerInput.buttons == 64 and serializerInput.move.X == 0, "Serializer adapter produces compatible payload fields")
check(resolver:IsPressed(a, Input.Light), "Pressed is queryable")
check(resolver:GetLastPressedFrame(a, Input.Light) == 100, "LastPressedFrame is stored")
check(resolver:GetInputFrame(a, 100) == frame, "Historical frame is queryable")
check(resolver:GetInputFrame(b, 100) == nil, "Entity history is isolated")
check(resolver:GetEvents()[1].Type == InputEvent.Type.Pressed, "Pressed event is emitted")
check(resolver:GetEvents()[1].EntityId == a.Id and resolver:GetEvents()[1].InputId == Input.Light, "Event identifies input")
check(resolver:GetEvents()[1].Frame == 100 and resolver:GetEvents()[1].Source == "Test", "Event stores metadata")
resolver:AdvanceFrame(a, 101, "Test")
check(resolver:IsHeld(a, Input.Light), "Pressed advances to Held")
check(InputPacketAdapter.ToButtons(resolver:GetInputFrame(a, 101)) == 64, "Held input remains active in packet form")
check(resolver:GetHeldDuration(a, Input.Light, 105) == 5, "Held duration uses frames")
check(resolver:WasPressedWithin(a, Input.Light, 5, 105), "Pressed window includes lower boundary")
check(not resolver:WasPressedWithin(a, Input.Light, 4, 105), "Pressed window excludes older frames")
resolver:SetInput(a, Input.Forward, InputState.Pressed, 100)
resolver:SetInput(a, Input.Guard, InputState.Pressed, 100)
check(resolver:IsPressed(a, Input.Forward) and resolver:IsPressed(a, Input.Guard), "Inputs coexist")
check(resolver:GetInputFrame(a, 100).Inputs[Input.Forward] == InputState.Pressed, "Same frame keeps Forward")
check(resolver:GetInputFrame(a, 100).Inputs[Input.Guard] == InputState.Pressed, "Same frame keeps Guard")
resolver:SetInput(a, Input.Light, InputState.Released, 102)
check(resolver:IsReleased(a, Input.Light), "Released is queryable")
check(resolver:GetLastReleasedFrame(a, Input.Light) == 102, "LastReleasedFrame is stored")
check(resolver:WasReleasedWithin(a, Input.Light, 0, 102), "Released window includes exact frame")
resolver:AdvanceFrame(a, 103)
check(resolver:GetInput(a, Input.Light) == InputState.None, "Released advances to None")
resolver:SetInput(a, Input.Light, InputState.Pressed, 104)
check(resolver:IsPressed(a, Input.Light), "Re-press is recognized")
check(resolver:GetLastPressedFrame(a, Input.Light) == 104, "Re-press updates timestamp")
resolver:SetInput(a, Input.Light, InputState.Pressed, 104)
check(resolver:IsPressed(a, Input.Light), "Duplicate same-frame press remains Pressed")
check(#resolver:GetRecentInputs(a, 100, 104) <= 5, "Buffer is bounded")
check(resolver:GetRecentInputs(a, 100, 104)[1].Frame >= 100, "Buffer retains recent frames")
check(resolver:GetInputFrame(a, 90) == nil, "Old frames are unavailable")
check(resolver:SetInput(a, Input.Heavy, InputState.Pressed, 105) ~= nil, "Another input is accepted")
check(resolver:IsPressed(a, Input.Heavy), "Heavy is independent")
check(not resolver:IsPressed(b, Input.Heavy), "Entity B remains isolated")
check(resolver:SetInput(b, Input.Special, InputState.Pressed, 100) ~= nil, "Entity B accepts input")
check(resolver:IsPressed(b, Input.Special), "Entity B state is queryable")
check(not resolver:IsPressed(c, Input.Special), "Entity C remains isolated")
check(type(resolver:GetInputFrame(a, 105).Inputs) == "table", "Frame inputs are serializable data")
resolver:Reset(a)
check(resolver:GetInput(a, Input.Light) == InputState.None, "Reset clears current inputs")
check(resolver:GetLastPressedFrame(a, Input.Light) == nil, "Reset clears temporal metadata")
check(resolver:GetInputFrame(a, 104) == nil, "Reset clears history")
check(resolver:GetInput(b, Input.Special) == InputState.Pressed, "Reset is entity-local")
check(world:GetInputResolver() == resolver, "World exposes InputResolver")
check(type(resolver.SetInput) == "function" and type(resolver.GetInput) == "function", "Public input API exists")
check(type(resolver.WasPressedWithin) == "function" and type(resolver.GetHeldDuration) == "function", "Temporal query API exists")
check(#resolver:GetEvents() > 0, "Events remain available")
resolver:Clear()
check(#resolver:GetEvents() == 0, "Clear removes transient events")
resolver:Reset(b)
resolver:Reset(c)
for index, inputId in ipairs({
	Input.Up, Input.Down, Input.Left, Input.Right, Input.Forward, Input.Back,
	Input.Light, Input.Medium, Input.Heavy, Input.Special, Input.Guard, Input.Jump, Input.Dash,
}) do
	local testEntity = index % 2 == 0 and b or c
	check(resolver:SetInput(testEntity, inputId, InputState.Pressed, 200 + index) ~= nil,
		"Distinct inputs can be recorded")
	check(resolver:IsPressed(testEntity, inputId), "Distinct input state is isolated")
	check(resolver:GetInputFrame(testEntity, 200 + index).Inputs[inputId] == InputState.Pressed,
		"Distinct input is represented in its frame")
	check(resolver:GetLastPressedFrame(testEntity, inputId) == 200 + index,
		"Distinct input keeps its press frame")
	check(resolver:WasPressedWithin(testEntity, inputId, 0, 200 + index),
		"Distinct input supports exact temporal queries")
	check(not resolver:IsReleased(testEntity, inputId), "Distinct input is not released")
	check(not resolver:IsHeld(testEntity, inputId), "Distinct input is not held on press frame")
end
print("Combat input tests passed (" .. tostring(cases) .. " cases)")
