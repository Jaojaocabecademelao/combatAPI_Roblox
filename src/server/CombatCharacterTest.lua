return function()
local Shared = game:GetService("ReplicatedStorage"):WaitForChild("Shared")
local Core, Combat = Shared:WaitForChild("Core"), Shared:WaitForChild("Combat")
local World = require(Core.World)
local EntityState = require(Core.EntityState)
local CharacterProfile = require(Combat.CharacterProfile)
local CharacterAdapter = require(Combat.CharacterAdapter)
local CharacterRepresentation = require(Combat.CharacterRepresentation)
local CharacterComponent = require(Combat.CharacterComponent)
local CharacterResult = require(Combat.CharacterResult)
local CharacterEvent = require(Combat.CharacterEvent)

local cases = 0
local function check(value, message)
	assert(value, message or ("Character assertion " .. tostring(cases + 1) .. " failed"))
	cases += 1
end
local function expectFailure(result, kind)
	check(result.Type == kind and not result.Accepted, "Expected " .. kind)
end

local world = World.new()
local resolver = world:GetCharacterResolver()
local profile = CharacterProfile.new({
	CharacterId = "SharedFighter", DisplayName = "Shared Fighter",
	AdapterId = "Custom", RepresentationType = "Proxy",
	InputProfileId = "InputA", MovementStateProfileId = "MovementA",
	DefaultConfiguration = { Variant = "Default" },
	Data = { Archetype = "Rushdown" },
})
local profile2 = CharacterProfile.new({ CharacterId = "SecondFighter", AdapterId = "R15" })
local validRepresentations = {}
local function representationValue(value)
	return getmetatable(value) == CharacterRepresentation and value:GetValue() or value
end
local adapter = CharacterAdapter.new("Custom", {
	IsValid = function(value) local raw = representationValue(value); return raw ~= nil and raw.Valid == true end,
	Attach = function(entityId, value) validRepresentations[value] = entityId; return true end,
	Detach = function(entityId, value) validRepresentations[value] = nil; return true end,
})
local r6 = CharacterAdapter.new("R6", { IsValid = function(value) return value and value.Rig == "R6" end })
local r15 = CharacterAdapter.new("R15", { IsValid = function(value) return value and value.Rig == "R15" end })
local custom = CharacterAdapter.new("Custom2", { IsValid = function(value) local raw = representationValue(value); return raw and raw.Custom end })
check(resolver:RegisterProfile(profile), "Profile registers")
check(resolver:RegisterProfile(profile2), "Second profile registers")
check(resolver:RegisterAdapter("Custom", adapter), "Adapter registers")
check(resolver:RegisterAdapter("R6", r6), "R6 adapter registers")
check(resolver:RegisterAdapter("R15", r15), "R15 adapter registers")
check(resolver:RegisterAdapter("Custom2", custom), "Custom adapter registers")
check(resolver:GetProfile("SharedFighter") == profile, "Profile retrieves")
check(resolver:GetAdapterDefinition("R6") == r6, "R6 adapter retrieves")
check(not resolver:RegisterProfile({}), "Invalid profile rejected")
check(not resolver:RegisterAdapter("Bad", {}), "Invalid adapter rejected")
check(profile:GetData().Archetype == "Rushdown", "Profile data is available")
local copied = profile:GetData(); copied.Archetype = "Changed"
check(profile:GetData().Archetype == "Rushdown", "Profile data is copied")
local entityA, entityB, entityC = world:CreateEntity(), world:CreateEntity(), world:CreateEntity()
check(world:GetCharacterResolver() == resolver, "World exposes stable resolver")
check(not resolver:IsAttached(entityA), "New entity is unattached")
check(resolver:GetCharacter(entityA) == nil, "No character before attach")
check(resolver:IsValid(entityA), "Entity is valid without character")
local representationA = CharacterRepresentation.new({ Valid = true }, "Proxy")
local attached = resolver:Attach(entityA, representationA, { Profile = profile, Frame = 10 })
check(attached.Type == CharacterResult.Type.Success and attached.Accepted, "Attach succeeds")
check(world:GetCharacterResolver() == resolver and world.AttachCharacter ~= nil,
	"World exposes character lifecycle helpers")
check(resolver:GetAdapterDefinition("RobloxHumanoid") ~= nil,
	"World provides the Roblox Humanoid adapter")
check(resolver:GetAdapterDefinition("RobloxHumanoid").GetRoot ~= nil
	and resolver:GetAdapterDefinition("RobloxHumanoid").GetPart ~= nil,
	"Roblox adapter exposes presentation lookup callbacks")
check(resolver:IsAttached(entityA), "Attach marks component")
check(resolver:GetCharacterId(entityA) == "SharedFighter", "Character identity is separate")
check(resolver:GetRepresentation(entityA) == representationA, "Representation retrieves")
check(resolver:GetAdapter(entityA) == adapter, "Adapter retrieves")
check(resolver:GetCharacter(entityA).EntityId == entityA.Id, "Component stores entity id")
check(resolver:GetCharacter(entityA).AttachedFrame == 10, "Attach frame is deterministic")
check(resolver:GetCharacter(entityA).Lifecycle == "Attached", "Lifecycle is attached")
check(validRepresentations[representationA] == entityA.Id, "Adapter attach hook runs")
check(resolver:GetEvents()[1].Type == CharacterEvent.Type.Attached, "Attach event emitted")
check(resolver:GetEvents()[1].EntityId == entityA.Id, "Attach event identifies entity")
check(resolver:GetEvents()[1].Frame == 10, "Attach event stores frame")
expectFailure(resolver:Attach(entityA, representationA, { Profile = profile, Frame = 10 }), CharacterResult.Type.AlreadyAttached)
expectFailure(resolver:Attach(entityA, nil, { Profile = profile, Frame = 11 }), CharacterResult.Type.InvalidRepresentation)
expectFailure(resolver:Attach(entityB, { Valid = false }, { Profile = profile, Frame = 11 }), CharacterResult.Type.AdapterRejected)
expectFailure(resolver:Attach(entityB, { Valid = true }, { Frame = 11 }), CharacterResult.Type.InvalidProfile)
expectFailure(resolver:Attach(9999, representationA, { Profile = profile, Frame = 11 }), CharacterResult.Type.InvalidEntity)
local detached = resolver:Detach(entityA, { Frame = 20 })
check(detached.Accepted, "Detach succeeds")
check(not resolver:IsAttached(entityA), "Detach clears association")
check(resolver:GetCharacterId(entityA) == nil, "Detach clears character identity")
check(resolver:GetRepresentation(entityA) == nil, "Detach clears representation")
check(resolver:GetCharacter(entityA).DetachedFrame == 20, "Detach frame is stored")
check(resolver:GetCharacter(entityA).Lifecycle == "Unattached", "Lifecycle is unattached")
check(validRepresentations[representationA] == nil, "Adapter detach hook runs")
check(resolver:GetEvents()[#resolver:GetEvents()].Type == CharacterEvent.Type.Detached, "Detach event emitted")
expectFailure(resolver:Detach(entityA, { Frame = 21 }), CharacterResult.Type.NotAttached)
check(world:GetEntity(entityA.Id) == entityA, "Detach preserves entity")
local representationB = CharacterRepresentation.new({ Valid = true }, "Proxy")
local reattached = resolver:Reattach(entityA, representationB, { Profile = profile, Frame = 30 })
check(reattached.Accepted and resolver:IsAttached(entityA), "Reattach after detach succeeds")
check(resolver:GetRepresentation(entityA) == representationB, "Reattach stores new representation")
check(resolver:GetCharacter(entityA).AttachedFrame == 30, "Reattach stores new frame")
local old = resolver:GetRepresentation(entityA)
local failedReattach = resolver:Reattach(entityA, { Valid = false }, { Profile = profile, Frame = 31 })
expectFailure(failedReattach, CharacterResult.Type.AdapterRejected)
check(resolver:GetRepresentation(entityA) == old, "Failed reattach preserves old representation")
local representationC = CharacterRepresentation.new({ Valid = true }, "Proxy")
local reattached2 = resolver:Reattach(entityA, representationC, { Profile = profile2, Adapter = adapter, Frame = 32 })
check(reattached2.Accepted, "Reattach can change profile")
check(resolver:GetCharacterId(entityA) == "SecondFighter", "Reattach changes character id")
check(resolver:GetEvents()[#resolver:GetEvents()].Type == CharacterEvent.Type.Reattached, "Reattach event emitted")
local c1 = resolver:Attach(entityB, { Rig = "R6" }, { Profile = CharacterProfile.new({ CharacterId = "R6Fighter", AdapterId = "R6" }), Frame = 40 })
check(c1.Accepted, "R6 representation attaches")
local c2 = resolver:Attach(entityC, { Rig = "R15" }, { Profile = CharacterProfile.new({ CharacterId = "R15Fighter", AdapterId = "R15" }), Frame = 40 })
check(c2.Accepted, "R15 representation attaches")
check(resolver:GetAdapter(entityB) == r6 and resolver:GetAdapter(entityC) == r15, "R6 and R15 coexist")
check(resolver:Detach(entityB, { Frame = 41 }).Accepted, "R6 detaches")
check(resolver:Reattach(entityC, { Rig = "R15" }, { Profile = CharacterProfile.new({ CharacterId = "R6Again", AdapterId = "R6" }), Frame = 42 }).Type == CharacterResult.Type.AdapterRejected, "Mismatched R15 representation rejects an R6 reattach")
check(resolver:GetCharacterId(entityC) == "R15Fighter", "Invalid reattach preserves R15")
local dummy = world:CreateEntity()
local dummyProfile = CharacterProfile.new({ CharacterId = "Dummy", AdapterId = "Custom2" })
check(resolver:Attach(dummy, { Custom = true }, { Profile = dummyProfile, Frame = 50 }).Accepted, "Dummy attaches")
check(resolver:Detach(dummy, { Frame = 51 }).Accepted, "Dummy detaches")
local npc = world:CreateEntity()
check(resolver:Attach(npc, { Valid = true }, { Profile = profile, Frame = 52 }).Accepted, "NPC-like data attaches")
check(resolver:GetCharacter(npc).EntityId == npc.Id, "NPC has same infrastructure")
check(resolver:GetCharacter(npc).Profile == profile, "NPC does not require Player")
entityB.State = EntityState.Dead
expectFailure(resolver:Attach(entityB, { Rig = "R6" }, { Profile = profile2, Adapter = r6, Frame = 60 }), CharacterResult.Type.EntityDead)
check(resolver:Detach(entityB, { Frame = 61 }).Type == CharacterResult.Type.NotAttached, "Dead detach remains allowed")
entityA.State = EntityState.Dead
expectFailure(resolver:Reattach(entityA, representationA, { Profile = profile, Frame = 62 }), CharacterResult.Type.EntityDead)
check(resolver:GetCharacterId(entityA) == "SecondFighter", "Dead reattach preserves state")
local independent = world:CreateEntity()
check(resolver:IsValid(independent), "Entity remains valid without character")
check(world:GetEntity(independent.Id) == independent, "Core registry is independent")
check(resolver:Detach(9999, { Frame = 70 }).Type == CharacterResult.Type.InvalidEntity, "Invalid detach is explicit")
check(resolver:Reattach(9999, representationA, { Profile = profile, Frame = 70 }).Type == CharacterResult.Type.InvalidEntity, "Invalid reattach is explicit")
check(resolver:GetResults()[1] ~= nil, "Results are retained")
check(resolver:GetEvents()[1].EntityId == entityA.Id, "Events retain context")
check(type(resolver.On) == "function", "Event subscription exists")
local observed = 0
resolver:On(CharacterEvent.Type.Attached, function(event) observed += event.EntityId > 0 and 1 or 0 end)
local listenerEntity = world:CreateEntity()
check(resolver:Attach(listenerEntity, representationA, { Profile = profile, Frame = 80 }).Accepted, "Listener attach succeeds")
check(observed == 1, "Listener receives event")
check(type(resolver.GetProfile) == "function" and type(resolver.GetAdapterDefinition) == "function", "Registry API exists")
check(type(resolver.GetCharacter) == "function" and type(resolver.GetRepresentation) == "function", "Query API exists")
check(profile.CharacterId ~= entityA.Id, "CharacterId is not EntityId")
check(profile.InputProfileId == "InputA", "Input profile metadata is preserved")
check(profile.MovementStateProfileId == "MovementA", "Movement profile metadata is preserved")
check(profile.RepresentationType == "Proxy", "Representation metadata is preserved")
check(profile.DefaultConfiguration.Variant == "Default", "Default configuration is preserved")
check(resolver:GetCharacter(entityA).Profile == profile2, "Runtime profile is per entity")
check(resolver:GetCharacter(entityC).Profile.CharacterId == "R15Fighter", "Entity C profile is isolated")
check(resolver:GetCharacter(npc).Profile == profile, "NPC profile is isolated")
check(resolver:GetCharacter(entityA).Attached, "Entity A remains attached")
check(resolver:GetCharacter(entityA).Adapter == adapter, "Entity A keeps its adapter")
check(resolver:GetCharacter(entityA).Representation == representationC, "Entity A keeps newest representation")
check(resolver:GetCharacter(entityA).AttachedFrame == 32, "Entity A keeps reattach frame")
check(resolver:GetCharacter(entityA).DetachedFrame == nil, "Attached entity has no detached frame")
check(resolver:GetCharacter(entityC).Attached, "Entity C remains attached")
check(resolver:GetCharacter(entityC).Adapter == r15, "Entity C keeps R15 adapter")
check(resolver:GetCharacter(entityC).AttachedFrame == 40, "Entity C keeps original attach frame")
check(resolver:GetCharacter(npc).Attached, "NPC remains attached")
check(resolver:GetCharacter(npc).AttachedFrame == 52, "NPC frame is independent")
check(resolver:GetCharacter(listenerEntity).Attached, "Listener entity remains attached")
check(resolver:GetCharacter(listenerEntity).EntityId == listenerEntity.Id, "Listener entity identity is correct")
check(resolver:GetCharacter(entityA).EntityId ~= resolver:GetCharacter(entityC).EntityId, "Runtime identities are distinct")
check(resolver:GetCharacter(entityA).Profile ~= resolver:GetCharacter(entityC).Profile, "Profiles can differ per entity")
check(resolver:GetCharacter(npc).Profile == profile, "Shared profile is reused safely")
check(profile:GetData().Archetype == "Rushdown", "Shared profile was not mutated by runtime")
check(resolver:GetProfile("Unknown") == nil, "Unknown profile is absent")
check(resolver:GetAdapterDefinition("Unknown") == nil, "Unknown adapter is absent")
check(resolver:RemoveProfile("Unknown"), "Removing unknown profile is deterministic")
check(resolver:RemoveAdapter("Unknown"), "Removing unknown adapter is deterministic")
local adapterRemoved = CharacterAdapter.new("Temporary", { IsValid = function(value) return value ~= nil end })
check(resolver:RegisterAdapter("Temporary", adapterRemoved), "Temporary adapter registers")
check(resolver:GetAdapterDefinition("Temporary") == adapterRemoved, "Temporary adapter is retrievable")
check(resolver:RemoveAdapter("Temporary"), "Temporary adapter removes")
check(resolver:GetAdapterDefinition("Temporary") == nil, "Removed adapter is absent")
local profileRemoved = CharacterProfile.new({ CharacterId = "TemporaryProfile" })
check(resolver:RegisterProfile(profileRemoved), "Temporary profile registers")
check(resolver:GetProfile("TemporaryProfile") == profileRemoved, "Temporary profile is retrievable")
check(resolver:RemoveProfile("TemporaryProfile"), "Temporary profile removes")
check(resolver:GetProfile("TemporaryProfile") == nil, "Removed profile is absent")
check(CharacterRepresentation.new("dummy").Type == "Custom", "Representation default type is abstract")
check(CharacterRepresentation.new("dummy"):IsValid(), "Representation validates nonnil value")
check(CharacterRepresentation.new(nil):IsValid() == false, "Nil representation is invalid")
check(CharacterRepresentation.new("dummy"):GetValue() == "dummy", "Representation exposes value")
check(adapter:Validate(representationA), "Adapter validates compatible representation")
check(not adapter:Validate({ Valid = false }), "Adapter rejects incompatible representation")
check(r6:Validate({ Rig = "R6" }), "R6 contract validates R6")
check(not r6:Validate({ Rig = "R15" }), "R6 contract rejects R15")
check(r15:Validate({ Rig = "R15" }), "R15 contract validates R15")
check(not r15:Validate({ Rig = "R6" }), "R15 contract rejects R6")
check(custom:Validate({ Custom = true }), "Custom contract validates custom representation")
check(not custom:Validate({ Valid = true }), "Custom contract rejects unrelated representation")
check(resolver:GetEvents()[1].Result ~= nil, "Events include result context")
check(resolver:GetResults()[1].EntityId == entityA.Id, "Results include entity context")
check(resolver:GetResults()[1].Frame == 10, "Results include frame context")
check(resolver:GetResults()[1].Accepted, "Successful results are accepted")
local failedEvents = {}
resolver:On(CharacterEvent.Type.AttachFailed, function(event) table.insert(failedEvents, event) end)
expectFailure(resolver:Attach(world:CreateEntity(), { Valid = false }, { Profile = profile, Frame = 90 }), CharacterResult.Type.AdapterRejected)
check(#failedEvents == 1, "Failed attach event is observable")
check(failedEvents[1].Frame == 90, "Failed event carries frame")
check(failedEvents[1].Result == CharacterResult.Type.AdapterRejected, "Failed event carries reason")
local sameFrame = world:CreateEntity()
check(resolver:Attach(sameFrame, representationA, { Profile = profile, Frame = 100 }).Accepted, "Same-frame first attach succeeds")
check(resolver:Attach(sameFrame, representationA, { Profile = profile, Frame = 100 }).Type == CharacterResult.Type.AlreadyAttached, "Same-frame duplicate is stable")
check(resolver:Detach(sameFrame, { Frame = 100 }).Accepted, "Same-frame detach succeeds")
check(resolver:Detach(sameFrame, { Frame = 100 }).Type == CharacterResult.Type.NotAttached, "Same-frame duplicate detach is stable")
check(resolver:Attach(sameFrame, representationA, { Profile = profile, Frame = 100 }).Accepted, "Same-frame reattach after detach succeeds")
check(resolver:GetCharacter(sameFrame).AttachedFrame == 100, "Same-frame attach frame is preserved")
check(resolver:GetCharacter(sameFrame).DetachedFrame == nil, "Reattach clears prior detached marker")
check(resolver:GetCharacter(sameFrame).Lifecycle == "Attached", "Same-frame lifecycle remains valid")
check(resolver:IsAttached(sameFrame), "Same-frame final state is attached")
check(world:GetEntity(sameFrame.Id) == sameFrame, "Same-frame operations preserve entity")
check(resolver:Detach(sameFrame, { Frame = 101 }).Accepted, "Final cleanup succeeds")
check(not resolver:IsAttached(sameFrame), "Final cleanup leaves unattached state")
check(resolver:GetCharacter(sameFrame).DetachedFrame == 101, "Final cleanup records detach frame")
resolver:Clear()
check(#resolver:GetEvents() == 0 and #resolver:GetResults() == 0, "Transient resolver history clears")
print("Combat character tests passed (" .. tostring(cases) .. " cases)")

end
